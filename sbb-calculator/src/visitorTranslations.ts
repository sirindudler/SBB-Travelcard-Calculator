// Translation helper for the visitor guide. Falls back to English (e.g. for Romansh).
export const useVisitorTranslation = (language: Language) => {
  return {
    t: (key: string, params?: Record<string, string | number>) => {
      let text = visitorTranslations[language]?.[key] ?? visitorTranslations.en[key] ?? key;
      if (params) {
        Object.entries(params).forEach(([param, value]) => {
          text = text.replace(`{${param}}`, String(value));
        });
      }
      return text;
    }
  };
};
